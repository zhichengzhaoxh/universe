const languageButton = document.getElementById("language-button");
const savedLanguage = localStorage.getItem("universe-language");
let currentLanguage = translations[savedLanguage] ? savedLanguage : "en";
let selectedPlanetId = "mercury";
let animationPaused = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

function applyLanguage() {
  const text = translations[currentLanguage];
  document.documentElement.lang = currentLanguage;
  document.title = text.solarTitle;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = text[element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", text[element.dataset.i18nAriaLabel]);
  });

  languageButton.textContent = currentLanguage === "en" ? "中文" : "English";
  languageButton.setAttribute("aria-label", text.changeLanguage);
  renderPlanet(selectedPlanetId);
  updateAnimationControl();
}

function renderPlanet(planetId) {
  const body = planetId === sun.id ? sun : planets.find((item) => item.id === planetId);
  if (!body) return;

  selectedPlanetId = planetId;
  const text = translations[currentLanguage];
  document.getElementById("planet-detail-title").textContent = text[body.id];
  document.getElementById("body-profile-label").textContent =
    text[planetId === sun.id ? "starProfile" : "planetProfile"];
  document.getElementById("planet-type").textContent = text[body.type];
  document.getElementById("planet-fact").textContent = text[body.fact];

  const numberLocale = currentLanguage === "zh" ? "zh-CN" : "en-US";
  document.getElementById("planet-diameter-label").textContent = text[
    planetId === sun.id ? "sunDiameterLabel" : "diameterLabel"
  ];
  document.getElementById("planet-diameter").textContent =
    `${body.diameter.toLocaleString(numberLocale)} km`;

  if (planetId === sun.id) {
    document.getElementById("planet-distance-label").textContent = text.starTypeLabel;
    document.getElementById("planet-distance").textContent = text.starMass;
    document.getElementById("planet-period-label").textContent = text.surfaceTemperatureLabel;
    document.getElementById("planet-period").textContent = text.sunTemperature;
    document.getElementById("planet-moons-label").textContent = text.ageLabel;
    document.getElementById("planet-moons").textContent = text.sunAge;
    document.getElementById("au-note").textContent = text.sunDiameterNote;
    document.getElementById("kepler-result").classList.add("kepler-result-note");
    document.getElementById("kepler-check").textContent = text.sunKeplerNote;
    document.getElementById("kepler-ratio").textContent = "";
    document.getElementById("kepler-units").textContent = "";
  } else {
    document.getElementById("planet-distance-label").textContent = text.distanceLabel;
    document.getElementById("planet-distance").textContent = `${body.distanceAu.toLocaleString(numberLocale, { maximumFractionDigits: 3 })} AU`;
    document.getElementById("planet-period-label").textContent = text.periodLabel;
    document.getElementById("planet-period").textContent = currentLanguage === "zh"
      ? `${body.periodDays.toLocaleString(numberLocale)} 天（${body.periodYears.toLocaleString(numberLocale, { maximumFractionDigits: 3 })} 地球年）`
      : `${body.periodDays.toLocaleString(numberLocale)} days (${body.periodYears.toLocaleString(numberLocale, { maximumFractionDigits: 3 })} Earth years)`;
    document.getElementById("planet-moons-label").textContent = text.moonsLabel;
    document.getElementById("planet-moons").textContent = text[body.moons];
    document.getElementById("au-note").textContent = text.auNote;
    document.getElementById("kepler-result").classList.remove("kepler-result-note");
    document.getElementById("kepler-check").textContent = text.keplerCheck;
    document.getElementById("kepler-ratio").textContent =
      (body.distanceAu ** 3 / body.periodYears ** 2).toLocaleString(
        numberLocale,
        { maximumFractionDigits: 3 }
      );
    document.getElementById("kepler-units").textContent = text.keplerUnits;
  }

  document.querySelectorAll(".planet-choice").forEach((button) => {
    const selected = button.dataset.planet === planetId;
    button.classList.toggle("is-selected", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
  document.getElementById("orbit-visual").dataset.selected = planetId;
  renderSizeComparison(planetId === sun.id ? null : planetId);
}

function renderSizeComparison(selectedId) {
  const container = document.getElementById("size-comparison");
  const maxDiameter = Math.max(...planets.map((planet) => planet.diameter));

  container.innerHTML = planets.map((planet) => {
    const size = Math.max(8, (planet.diameter / maxDiameter) * 68);
    const selectedClass = planet.id === selectedId ? " is-selected" : "";
    return `
      <button class="size-planet${selectedClass}" type="button" data-planet="${planet.id}" aria-pressed="${planet.id === selectedId}">
        <span class="size-orb ${planet.id}-swatch" style="--planet-size: ${size.toFixed(1)}px" aria-hidden="true"></span>
        <span class="size-planet-name">${translations[currentLanguage][planet.id]}</span>
        <span class="size-planet-value">${planet.diameter.toLocaleString(currentLanguage === "zh" ? "zh-CN" : "en-US")} km</span>
        <span class="size-earth-ratio">${(planet.diameter / 12756).toLocaleString(currentLanguage === "zh" ? "zh-CN" : "en-US", { maximumFractionDigits: 2 })} ${translations[currentLanguage].relativeEarth}</span>
      </button>
    `;
  }).join("");

  container.querySelectorAll(".size-planet").forEach((button) => {
    button.addEventListener("click", () => renderPlanet(button.dataset.planet));
  });
}

function updateAnimationControl() {
  const toggle = document.getElementById("orbit-toggle");
  const text = translations[currentLanguage];
  toggle.textContent = animationPaused ? text.playOrbits : text.pauseOrbits;
  toggle.setAttribute("aria-pressed", String(animationPaused));
  document.getElementById("orbit-visual").classList.toggle("is-paused", animationPaused);
  document.getElementById("orbit-visual").classList.toggle("motion-enabled", !animationPaused);
}

document.querySelectorAll(".planet-choice").forEach((button) => {
  button.addEventListener("click", () => renderPlanet(button.dataset.planet));
});

document.getElementById("orbit-toggle").addEventListener("click", () => {
  animationPaused = !animationPaused;
  updateAnimationControl();
});

const sunSelect = document.getElementById("sun-select");
sunSelect.addEventListener("click", () => renderPlanet(sun.id));
sunSelect.addEventListener("keydown", (event) => {
  if (event.key === "Enter" || event.key === " ") {
    event.preventDefault();
    renderPlanet(sun.id);
  }
});

languageButton.addEventListener("click", () => {
  currentLanguage = currentLanguage === "en" ? "zh" : "en";
  localStorage.setItem("universe-language", currentLanguage);
  applyLanguage();
});

applyLanguage();







